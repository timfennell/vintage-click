#!/usr/bin/env python3
"""Writes cross/shaders/spectra.glsl from Sources/SplatCamera/SpectraData.swift
(the Metal tables tools/make_spectra.py generates), so the Windows flare and
grating use the same numbers. Run again whenever SpectraData.swift changes:

    python cross/tools/spectra_glsl.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "Sources/SplatCamera/SpectraData.swift").read_text(encoding="utf-8")
body = src.split('"""')[1]

out = ["// Generated by cross/tools/spectra_glsl.py from Sources/SplatCamera/SpectraData.swift: do not edit.",
       "// The lamps' and gels' spectra, for the lens flare and the diffraction gratings."]


def braces_to_ctor(text, base, dims):
    """{a, b} -> base[n](a, b), nested for 2D (dims = [outer, inner])."""
    text = text.strip()
    assert text[0] == "{" and text[-1] == "}"
    inner = text[1:-1]
    if len(dims) == 1:
        return f"{base}[{dims[0]}]({inner})"
    parts, depth, cur = [], 0, ""
    for ch in inner:
        if ch == "{":
            depth += 1
        if ch == "}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    rows = [braces_to_ctor(p, base, dims[1:]) for p in parts]
    return f"{base}[{dims[0]}][{dims[1]}]({', '.join(rows)})"


for line in body.splitlines():
    s = line.strip()
    if not s:
        continue
    if s.startswith("//"):
        out.append(s)
        continue
    s = s.replace("float3(", "vec3(")
    m = re.match(r"constant (int|float|float3) (\w+)((?:\[\d+\])*) = (.*);(.*)$", s)
    if not m:
        raise SystemExit(f"cannot read: {s[:80]}")
    ty, name, dims, value, tail = m.groups()
    ty = {"float3": "vec3"}.get(ty, ty)
    dims = [int(d) for d in re.findall(r"\[(\d+)\]", dims)]
    if dims:
        value = braces_to_ctor(value, ty, dims)
        out.append(f"const {ty} {name}{''.join(f'[{d}]' for d in dims)} = {value};{tail}")
    else:
        out.append(f"const {ty} {name} = {value};{tail}")

(root / "cross/shaders/spectra.glsl").write_text("\n".join(out) + "\n", encoding="utf-8")
print("Wrote cross/shaders/spectra.glsl")
